// Translate only known application copy, never customer content or provider output.
const feedbackKeys: Record<string, TranslationKey> = {
  "Prospect created.": "prospectCreated",
  "Prospect updated.": "prospectUpdated",
  "Prospect deleted.": "prospectDeleted",
  "Service created.": "serviceCreated",
  "Service updated.": "serviceUpdated",
  "Service deleted.": "serviceDeleted",
  "Agency profile saved.": "agencySaved",
  "Proposal draft created.": "proposalCreated",
  "Proposal saved.": "proposalSaved",
  "Proposal summary and scope generated.": "proposalGenerated",
  "Delivery snapshot created.": "snapshotCreated",
  "Opportunities generated from the completed audit.": "opportunitiesGenerated",
  "AI insight generated for that opportunity.": "insightGenerated",
  "Audit completed and stored.": "auditCompleted",
  "Analysis is already in progress for this prospect.": "auditInProgress",
  "We could not load your workspace overview. Please try again.":
    "overviewError",
};

export function translateFeedback(message: string, locale: Locale) {
  const key = Object.hasOwn(feedbackKeys, message)
    ? feedbackKeys[message]
    : undefined;
  return key ? getDictionary(locale)[key] : message;
}
